//! `cargo xtask strongs-index`: regenerate the built-in Strong's index (#243),
//! `crates/engine/assets/strongs/index.tsv`, from STEPBible's TBESH and TBESG — the same
//! pinned files the Starter library's `tbesh` and `tbesg` Lexicons are built from, read through
//! `starter/sources.toml` so the index always matches the lock.
//!
//! One row per disambiguated Strong's number (`dStrong`), in file order, Hebrew then Greek:
//! `number <TAB> lemma <TAB> gloss`. The lemma is the first written form, without accents;
//! the gloss is STEPBible's brief gloss as written ("first: beginning": the word, then the
//! sense this number is for). The Meaning column is never read (TBESH's is not ours to ship).
//! The header names the sha256 of both inputs; a test checks it against the lock.
//!
//! The output is deterministic: the same inputs give the same bytes.

use std::collections::HashSet;
use std::path::Path;

use anyhow::{Context, Result, bail};
use obs_model::without_cantillation;
use obs_scripture::StrongsNumber;
use unicode_normalization::UnicodeNormalization;

use crate::starter::{Config, Lock, PinnedFile, fetch_file};

pub const OUT: &str = "crates/engine/assets/strongs/index.tsv";

/// The Starter Lexicons the index is made from, in output order.
pub const SOURCES: [&str; 2] = ["tbesh", "tbesg"];

const USAGE: &str = "usage: cargo xtask strongs-index [--cache <dir>]

Regenerates crates/engine/assets/strongs/index.tsv from the TBESH and TBESG files pinned in
starter/sources.toml (downloads are checked by sha256 and cached in target/starter-cache).";

/// Column positions in a TBES row.
const ESTRONG: usize = 0;
const DSTRONG: usize = 1;
const LEMMA: usize = 3;
const GLOSS: usize = 6;

pub fn run(root: &Path, args: &[String]) -> Result<()> {
    let mut cache = Config::defaults(root).cache;
    let mut it = args.iter();
    while let Some(a) = it.next() {
        match a.as_str() {
            "--cache" => {
                cache = it.next().context("--cache needs a directory")?.into();
            }
            "-h" | "--help" => {
                println!("{USAGE}");
                return Ok(());
            }
            other => bail!("unknown option `{other}`\n\n{USAGE}"),
        }
    }
    let pins = pinned(root)?;
    let mut inputs = Vec::new();
    for (id, pin) in &pins {
        let bytes = fetch_file(id, pin, &cache)?;
        let text = String::from_utf8(bytes).with_context(|| format!("{id} is not UTF-8"))?;
        inputs.push((id.clone(), pin.sha256.clone(), text));
    }
    let out = build(&inputs)?;
    let path = root.join(OUT);
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(&path, &out).with_context(|| format!("cannot write {}", path.display()))?;
    eprintln!(
        "strongs-index: wrote {} rows ({} bytes) to {OUT}",
        out.lines().filter(|l| !l.starts_with('#')).count(),
        out.len()
    );
    Ok(())
}

/// The pinned file of each of [`SOURCES`], from the Starter lock.
pub fn pinned(root: &Path) -> Result<Vec<(String, PinnedFile)>> {
    let lock = Lock::load(&root.join("starter/sources.toml"))?;
    SOURCES
        .iter()
        .map(|id| {
            let s = lock
                .sources
                .iter()
                .find(|s| s.resource_id == *id)
                .with_context(|| format!("starter/sources.toml has no `{id}`"))?;
            Ok((
                (*id).to_string(),
                PinnedFile {
                    url: s.url.clone(),
                    sha256: s.sha256.clone(),
                },
            ))
        })
        .collect()
}

/// The header line naming one input's sha256.
pub fn sha256_line(id: &str, sha256: &str) -> String {
    format!("# {id} sha256 {sha256}")
}

/// The index from each input's (resource id, sha256, text).
pub fn build(inputs: &[(String, String, String)]) -> Result<String> {
    let mut out = String::from(
        "# The built-in Strong's index (#243): number, lemma, gloss. Generated by\n\
         # `cargo xtask strongs-index` from STEPBible TBESH and TBESG (Translators Brief lexicons of\n\
         # Extended Strongs), STEP Bible, https://www.STEPBible.org, based on work at Tyndale House\n\
         # Cambridge, licensed CC BY 4.0. Changes: only the dStrong number, the first lemma form\n\
         # without accents, and the gloss; the Meaning, transliteration and morph columns left out.\n",
    );
    for (id, sha256, _) in inputs {
        out.push_str(&sha256_line(id, sha256));
        out.push('\n');
    }
    let mut seen = HashSet::new();
    for (id, _, text) in inputs {
        let rows = rows(text).with_context(|| format!("{id} is not a TBES file"))?;
        if rows.is_empty() {
            bail!("{id} has no entry rows");
        }
        for (number, lemma, gloss) in rows {
            // STEPBible tells a few individuals apart by letter case alone (H2148V, H2148v);
            // a Strong's number does not keep case, so the first is kept.
            if seen.insert(number) {
                out.push_str(&format!("{number}\t{lemma}\t{gloss}\n"));
            }
        }
    }
    Ok(out)
}

/// A TBES file's entry rows: (dStrong number, lemma, gloss).
fn rows(text: &str) -> Result<Vec<(StrongsNumber, String, String)>> {
    let lines: Vec<&str> = text.lines().collect();
    let header_at = lines
        .iter()
        .position(|l| {
            let mut f = l.split('\t');
            f.next().is_some_and(|c| c.trim().starts_with("eStrong"))
                && f.next().is_some_and(|c| c.trim() == "dStrong")
        })
        .context("no `eStrong  dStrong …` header row")?;
    // Whitespace collapsed, and in canonical (NFC) order: points come as typed in the source.
    let clean = |s: &str| {
        s.split_whitespace()
            .collect::<Vec<_>>()
            .join(" ")
            .nfc()
            .collect::<String>()
    };
    let mut out = Vec::new();
    for line in &lines[header_at + 1..] {
        let fields: Vec<&str> = line.split('\t').collect();
        if fields.len() <= GLOSS {
            continue;
        }
        let Ok(estrong) = fields[ESTRONG].trim().parse::<StrongsNumber>() else {
            continue;
        };
        // `H7225H = a Meaning of`: the number before the `=`.
        let dstrong = fields[DSTRONG]
            .split('=')
            .next()
            .and_then(|d| d.trim().parse::<StrongsNumber>().ok())
            .unwrap_or(estrong);
        let lemma = without_cantillation(fields[LEMMA].split(',').next().unwrap_or_default());
        let lemma = clean(&lemma);
        let gloss = clean(fields[GLOSS]);
        if lemma.is_empty() && gloss.is_empty() {
            continue;
        }
        out.push((dstrong, lemma, gloss));
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    const TBESH: &str = "Header text\n\
eStrong#\tdStrong\tuStrong\tHebrew\tTransliteration\tMorph\tGloss\tMeaning\n\
H0430\tH0430G = a Name of\tH3068G\tאֱלֹהִים\te.lo.him\tH:N-M\tGod\tThis name means\n\
H1254a\tH1254A =\tH1254A\tבָּרָא\tba.ra\tH:V\tto create\t1) to create\n\
H7225\tH7225G =\tH7225G\tרֵאשִׁית\tre.shit\tH:N-F\tfirst: beginning\t: beginning\n\
H7225\tH7225H = a Meaning of\tH7225G\tרֵאשִׁית\tre.shit\tH:N-F\tfirst: best\t: best\n\
H0776\tH0776G = in Hebrew of\tH0776H\tאֶ֫רֶץ\te.rets\tH:N-F\tland: country/planet\t1) land\n\
H2148V\tH2148V =\tH2148V\tזְכַרְיָה, זְכַרְיָהוּ\tze.khar.yah\tH:N-M-P\tZechariah\t\n\
H2148v\tH2148v =\tH2148v\tזְכַרְיָה\tze.khar.yah\tH:N-M-P\tZechariah\t\n\
\t==============\n";

    #[test]
    fn rows_keep_the_number_first_lemma_without_accents_and_gloss() {
        let out = build(&[("tbesh".into(), "abc".into(), TBESH.into())]).unwrap();
        assert!(out.contains("# tbesh sha256 abc\n"));
        let rows: Vec<&str> = out.lines().filter(|l| !l.starts_with('#')).collect();
        assert_eq!(
            rows,
            [
                "H430G\tאֱלֹהִים\tGod",
                "H1254A\tבָּרָא\tto create",
                "H7225G\tרֵאשִׁית\tfirst: beginning",
                "H7225H\tרֵאשִׁית\tfirst: best",
                "H776G\tאֶרֶץ\tland: country/planet",
                "H2148V\tזְכַרְיָה\tZechariah",
            ]
        );
        assert!(
            !out.contains("This name means"),
            "the Meaning column is never read"
        );
    }

    #[test]
    fn a_file_without_rows_is_refused() {
        assert!(build(&[("tbesh".into(), "abc".into(), "nothing".into())]).is_err());
    }

    /// The committed index was made from the files the Starter lock pins now.
    #[test]
    fn the_committed_index_names_the_pinned_sha256s() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap();
        let index = std::fs::read_to_string(root.join(OUT)).unwrap();
        for (id, pin) in pinned(root).unwrap() {
            let line = sha256_line(&id, &pin.sha256);
            assert!(
                index.lines().any(|l| l == line),
                "{OUT} was not made from the pinned {id}; run `cargo xtask strongs-index`"
            );
        }
    }
}
