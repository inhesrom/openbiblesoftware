//! Help → Credits (#67, #20 decision 4): every Starter Resource, the data built into the app,
//! the bundled fonts with their licence texts, third-party crates with theirs, and the test
//! data kept in the source repository.
//!
//! Nothing here is written by hand twice. The Credits are read from the files that already
//! carry the facts, compiled in:
//! - `ATTRIBUTION.toml`: every bundled asset (fonts, TVTMS, test excerpts), checked against the
//!   files by `cargo xtask assets`;
//! - `starter/sources.toml`: the Starter library lock (licence, Attribution, changes);
//! - `data/third-party-licenses.json`: generated by `cargo xtask licenses` (cargo-about) and
//!   checked by its CI gate;
//! - the fonts' own licence files ([`obs_fonts::FONT_LICENSES`]).
//!
//! It also finds a CC BY Starter Resource's published change record (`CHANGES-<id>.md`,
//! written by `cargo xtask starter`), which its About Tab links to.

use std::path::Path;
use std::sync::OnceLock;

use obs_model::{Manifest, cc_by_license_url, changes_record_file, is_cc_by};
use serde::Deserialize;

use crate::LibraryEntry;

const ATTRIBUTION_TOML: &str = include_str!("../../../ATTRIBUTION.toml");
const STARTER_LOCK: &str = include_str!("../../../starter/sources.toml");
const THIRD_PARTY_JSON: &str = include_str!("../data/third-party-licenses.json");

/// Where each release publishes the Starter library's change records (the `release`
/// workflow uploads them with the `.obr` files).
pub const PUBLISHED_CHANGES: &str =
    "https://github.com/inhesrom/openbiblesoftware/releases/latest/download/";

/// The Starter Resource whose votes rank the Cross-references Tool.
const OPENBIBLE_XREFS: &str = "openbible-xrefs";

/// What each piece of data built into the app is for, by `ATTRIBUTION.toml` path prefix.
const EMBEDDED_USE: &[(&str, &str)] = &[
    (
        "crates/formats/assets/tvtms/",
        "Built into the app: maps each Bible's verse numbering to the Standard versification \
         when the Bible is imported.",
    ),
    (
        "crates/engine/assets/reading-plans/",
        "Built into the app: the templates Tools → Reading plans makes plans from.",
    ),
];

/// One credited work.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Credit {
    pub name: String,
    /// SPDX licence expression.
    pub license: String,
    /// The Creative Commons deed, for CC BY licences.
    pub license_url: Option<String>,
    /// Where it comes from: a URL, or a description.
    pub source: String,
    /// Copyright or Attribution text, verbatim.
    pub credit: String,
    pub edition: Option<String>,
    /// "Changes we made".
    pub changes: Option<String>,
    /// What the app uses it for, when that is not obvious.
    pub note: Option<String>,
    /// A CC BY Starter Resource's id: it has a published change record.
    pub changes_record: Option<String>,
    /// The `ATTRIBUTION.toml` entry's path glob, for rows that come from it.
    pub asset: Option<String>,
    /// Licence texts shown with the row: (title, text).
    pub texts: Vec<(String, &'static str)>,
}

/// A titled group of Credits.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CreditSection {
    pub title: &'static str,
    pub intro: &'static str,
    pub credits: Vec<Credit>,
}

/// The third-party crate listing, as `cargo xtask licenses` writes it.
#[derive(Debug, Clone, Default, PartialEq, Eq, Deserialize)]
pub struct ThirdParty {
    pub generator: String,
    pub crates: Vec<ThirdPartyCrate>,
    pub licenses: Vec<ThirdPartyLicense>,
}

#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
pub struct ThirdPartyCrate {
    pub name: String,
    pub version: String,
    /// The SPDX expression the crate declares.
    pub license: String,
    #[serde(default)]
    pub repository: Option<String>,
}

/// One distinct licence text and the crates (`name version`) it covers.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
pub struct ThirdPartyLicense {
    pub id: String,
    pub name: String,
    pub used_by: Vec<String>,
    pub text: String,
}

/// Everything Help → Credits shows.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Credits {
    /// Starter library, data built into the app, fonts, and test data, in display order.
    pub sections: Vec<CreditSection>,
    pub third_party: ThirdParty,
    /// Embedded files that failed to parse (empty in a correct build; a test checks).
    pub problems: Vec<String>,
}

impl Credits {
    /// Every Credit in every section.
    pub fn all(&self) -> impl Iterator<Item = &Credit> {
        self.sections.iter().flat_map(|s| s.credits.iter())
    }
}

/// The Credits, parsed once from the compiled-in files.
pub fn credits() -> &'static Credits {
    static CREDITS: OnceLock<Credits> = OnceLock::new();
    CREDITS.get_or_init(|| build(ATTRIBUTION_TOML, STARTER_LOCK, THIRD_PARTY_JSON))
}

#[derive(Debug, Deserialize)]
struct AttributionFile {
    #[serde(default)]
    asset: Vec<AssetRow>,
}

/// One `[[asset]]` of `ATTRIBUTION.toml` (`xtask/src/assets.rs` validates the same shape).
#[derive(Debug, Clone, Deserialize)]
struct AssetRow {
    path: String,
    name: String,
    license: String,
    source: String,
    copyright: String,
    #[serde(default)]
    changes: Option<String>,
}

#[derive(Debug, Deserialize)]
struct LockFile {
    #[serde(rename = "source", default)]
    sources: Vec<LockSource>,
}

/// The parts of a `starter/sources.toml` entry the Credits show.
#[derive(Debug, Clone, Deserialize)]
struct LockSource {
    resource_id: String,
    title: String,
    url: String,
    #[serde(default)]
    origin_url: Option<String>,
    #[serde(default)]
    homepage: Option<String>,
    #[serde(default)]
    edition: Option<String>,
    spdx: String,
    attribution: String,
    changes: String,
}

impl AssetRow {
    fn credit(&self) -> Credit {
        Credit {
            name: self.name.clone(),
            license: self.license.clone(),
            license_url: cc_by_license_url(&self.license),
            source: self.source.clone(),
            credit: self.copyright.clone(),
            changes: self.changes.clone(),
            asset: Some(self.path.clone()),
            ..Credit::default()
        }
    }

    fn is_test_data(&self) -> bool {
        self.path.contains("/tests/")
    }

    fn is_font(&self) -> bool {
        obs_fonts::FONT_LICENSES
            .iter()
            .any(|f| self.path.starts_with(&format!("{}/", f.asset_dir)))
    }
}

impl LockSource {
    fn credit(&self) -> Credit {
        Credit {
            name: self.title.clone(),
            license: self.spdx.clone(),
            license_url: cc_by_license_url(&self.spdx),
            source: self
                .homepage
                .clone()
                .or_else(|| self.origin_url.clone())
                .unwrap_or_else(|| self.url.clone()),
            credit: self.attribution.clone(),
            edition: self.edition.clone(),
            changes: Some(self.changes.clone()),
            changes_record: is_cc_by(&self.spdx).then(|| self.resource_id.clone()),
            ..Credit::default()
        }
    }
}

fn build(attribution: &str, lock: &str, third_party: &str) -> Credits {
    let mut problems = Vec::new();
    let assets = toml::from_str::<AttributionFile>(attribution)
        .map(|f| f.asset)
        .unwrap_or_else(|e| {
            problems.push(format!("ATTRIBUTION.toml: {e}"));
            Vec::new()
        });
    let sources = toml::from_str::<LockFile>(lock)
        .map(|f| f.sources)
        .unwrap_or_else(|e| {
            problems.push(format!("starter/sources.toml: {e}"));
            Vec::new()
        });
    let third_party = serde_json::from_str::<ThirdParty>(third_party).unwrap_or_else(|e| {
        problems.push(format!("third-party-licenses.json: {e}"));
        ThirdParty::default()
    });

    let starter: Vec<Credit> = sources.iter().map(LockSource::credit).collect();

    let mut embedded: Vec<Credit> = assets
        .iter()
        .filter(|a| !a.is_test_data() && !a.is_font())
        .map(|a| {
            let mut c = a.credit();
            c.note = EMBEDDED_USE
                .iter()
                .find(|(prefix, _)| a.path.starts_with(prefix))
                .map(|(_, note)| (*note).to_string());
            c
        })
        .collect();
    if let Some(xrefs) = sources.iter().find(|s| s.resource_id == OPENBIBLE_XREFS) {
        let mut c = xrefs.credit();
        c.name = "OpenBible.info cross-reference votes".into();
        c.note = Some(format!(
            "The votes rank the Cross-references Tool's results. They ship as the Starter \
             Resource “{}”.",
            xrefs.title
        ));
        embedded.push(c);
    }

    let fonts: Vec<Credit> = assets
        .iter()
        .filter(|a| a.is_font())
        .map(|a| {
            let mut c = a.credit();
            c.texts = obs_fonts::FONT_LICENSES
                .iter()
                .filter(|f| a.path.starts_with(&format!("{}/", f.asset_dir)))
                .map(|f| (format!("{} licence ({})", f.family, f.file), f.text))
                .collect();
            c
        })
        .collect();

    let test_data: Vec<Credit> = assets
        .iter()
        .filter(|a| a.is_test_data())
        .map(AssetRow::credit)
        .collect();

    Credits {
        sections: vec![
            CreditSection {
                title: "Starter library",
                intro: "The Resources that come with the app. Each one's About Tab shows its \
                        Attribution in full; a CC BY Resource links to the published record of \
                        the changes we made.",
                credits: starter,
            },
            CreditSection {
                title: "Data built into the app",
                intro: "Open data the app itself uses.",
                credits: embedded,
            },
            CreditSection {
                title: "Fonts",
                intro: "Fonts for Resource text, with their licences. The interface's own \
                        fonts come with egui and are listed under Third-party software \
                        (epaint_default_fonts).",
                credits: fonts,
            },
            CreditSection {
                title: "Test data in the source code",
                intro: "Excerpts kept in the source repository as test fixtures. They are not \
                        part of the app; they are credited here with every other asset.",
                credits: test_data,
            },
        ],
        third_party,
        problems,
    }
}

/// The Help → Credits section for Resources downloaded from the Open catalogue (#134).
pub const OPEN_RESOURCES_TITLE: &str = "Downloaded open Resources";
pub const OPEN_RESOURCES_INTRO: &str = "Openly licensed Resources you downloaded from the Open \
     catalogue in Get Resources, credited from each one's own licence and Attribution.";

/// A Resource credited from its own manifest: licence, source, Attribution, edition and the
/// changes made.
pub fn manifest_credit(m: &Manifest) -> Credit {
    Credit {
        name: m.title.clone(),
        license: m.license.clone(),
        license_url: cc_by_license_url(&m.license),
        source: m.source_url.clone().unwrap_or_default(),
        credit: m.attribution.clone(),
        edition: m.edition.clone(),
        changes: m.changes.clone(),
        note: m
            .publisher
            .as_ref()
            .map(|p| format!("Downloaded from the Open catalogue (published by {p}).")),
        ..Credit::default()
    }
}

impl crate::Session {
    /// Help → Credits' Downloaded open Resources (#134): every Resource in the Library that
    /// was downloaded from the Open catalogue, by title, credited from its own manifest. A
    /// download is credited as soon as it is in the Library, and a removed one drops out.
    pub fn open_resource_credits(&self) -> Vec<Credit> {
        let mut out: Vec<Credit> = self
            .library
            .entries()
            .iter()
            .filter(|e| {
                self.imports
                    .report(&e.manifest.resource_id)
                    .is_some_and(|r| r.open_origin.is_some())
            })
            .map(|e| manifest_credit(&e.manifest))
            .collect();
        out.sort_by_key(|c| c.name.to_lowercase());
        out
    }
}

/// The published change record of a CC BY Starter Resource.
pub fn published_changes_url(resource_id: &str) -> String {
    format!("{PUBLISHED_CHANGES}{}", changes_record_file(resource_id))
}

/// Where a Resource's change record is, if it has one (a CC BY Starter Resource): the copy
/// installed beside its `.obr` (the installer bundles `dist/starter/`, records included) when
/// there is one, so it opens offline; else the copy published with the releases.
pub fn changes_record_url(entry: &LibraryEntry) -> Option<String> {
    changes_record_for(&entry.manifest, &entry.path)
}

fn changes_record_for(manifest: &Manifest, obr: &Path) -> Option<String> {
    if !manifest.has_changes_record() {
        return None;
    }
    let local = obr.with_file_name(changes_record_file(&manifest.resource_id));
    Some(if local.is_file() {
        file_url(&local)
    } else {
        published_changes_url(&manifest.resource_id)
    })
}

/// A `file://` URL for an absolute path, on any platform (`C:\a b` → `file:///C:/a%20b`).
pub fn file_url(path: &Path) -> String {
    let p = path.to_string_lossy().replace('\\', "/");
    let mut out = String::from("file://");
    if !p.starts_with('/') {
        out.push('/');
    }
    for c in p.chars() {
        match c {
            ' ' => out.push_str("%20"),
            '#' => out.push_str("%23"),
            '%' => out.push_str("%25"),
            '?' => out.push_str("%3F"),
            c => out.push(c),
        }
    }
    out
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

    use super::*;

    /// The workspace root, from this crate's manifest directory.
    fn root() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
    }

    #[test]
    fn the_compiled_in_files_all_parse() {
        let c = credits();
        assert!(c.problems.is_empty(), "{:?}", c.problems);
        assert!(c.sections.iter().all(|s| !s.credits.is_empty()));
        assert!(c.third_party.crates.len() > 100);
        assert!(!c.third_party.licenses.is_empty());
    }

    /// #67 acceptance: every asset row in ATTRIBUTION.toml appears in Credits, with its
    /// licence, source, copyright and changes. Parses the file on disk, not the compiled-in
    /// copy, so the test reads what `cargo xtask assets` checks.
    #[test]
    fn every_attribution_row_appears_in_credits() {
        let text = std::fs::read_to_string(root().join("ATTRIBUTION.toml")).unwrap();
        let file: toml::Table = toml::from_str(&text).unwrap();
        let rows = file["asset"].as_array().unwrap();
        assert!(rows.len() >= 15, "{} rows", rows.len());
        let credits = credits();
        for row in rows {
            let field = |k: &str| row.get(k).and_then(|v| v.as_str()).map(str::to_string);
            let path = field("path").unwrap();
            let shown: Vec<&Credit> = credits
                .all()
                .filter(|c| c.asset.as_deref() == Some(path.as_str()))
                .collect();
            assert_eq!(shown.len(), 1, "{path} is credited {} times", shown.len());
            let c = shown[0];
            assert_eq!(Some(c.name.clone()), field("name"), "{path}");
            assert_eq!(Some(c.license.clone()), field("license"), "{path}");
            assert_eq!(Some(c.source.clone()), field("source"), "{path}");
            assert_eq!(Some(c.credit.clone()), field("copyright"), "{path}");
            assert_eq!(c.changes, field("changes"), "{path}");
        }
    }

    #[test]
    fn every_starter_resource_is_credited_and_cc_by_ones_have_change_records() {
        let text = std::fs::read_to_string(root().join("starter/sources.toml")).unwrap();
        let lock: toml::Table = toml::from_str(&text).unwrap();
        let starter = &credits().sections[0];
        assert_eq!(starter.title, "Starter library");
        let sources = lock["source"].as_array().unwrap();
        assert_eq!(starter.credits.len(), sources.len());
        for (s, c) in sources.iter().zip(&starter.credits) {
            let id = s["resource_id"].as_str().unwrap();
            let spdx = s["spdx"].as_str().unwrap();
            assert_eq!(c.name, s["title"].as_str().unwrap());
            assert_eq!(c.credit, s["attribution"].as_str().unwrap());
            assert_eq!(c.changes.as_deref(), s["changes"].as_str());
            assert_eq!(
                c.changes_record.as_deref(),
                spdx.contains("CC-BY").then_some(id),
                "{id}"
            );
        }
    }

    #[test]
    fn tvtms_credits_step_bible_and_notes_the_changes() {
        let c = credits();
        let embedded = &c.sections[1];
        let tvtms = embedded
            .credits
            .iter()
            .find(|c| c.name.starts_with("TVTMS"))
            .unwrap();
        assert!(tvtms.credit.contains("STEP Bible"));
        assert!(tvtms.credit.contains("https://www.STEPBible.org"));
        assert!(tvtms.changes.as_deref().unwrap().contains("66-book canon"));
        assert_eq!(
            tvtms.license_url.as_deref(),
            Some("https://creativecommons.org/licenses/by/4.0/")
        );
        assert!(tvtms.note.is_some());
        let votes = embedded
            .credits
            .iter()
            .find(|c| c.name == "OpenBible.info cross-reference votes")
            .unwrap();
        assert_eq!(votes.license, "CC-BY-4.0");
        assert!(votes.credit.contains("OpenBible.info"));
    }

    #[test]
    fn each_font_carries_its_full_licence_text() {
        let fonts = &credits().sections[2];
        assert_eq!(fonts.credits.len(), obs_fonts::FONT_LICENSES.len());
        for f in &fonts.credits {
            assert_eq!(f.texts.len(), 1, "{}", f.name);
            assert!(
                f.texts[0].1.contains("SIL OPEN FONT LICENSE Version 1.1"),
                "{}",
                f.name
            );
        }
    }

    #[test]
    fn a_broken_file_is_reported_not_fatal() {
        let c = build("[[asset]]\npath = 1", "", "{");
        assert_eq!(c.problems.len(), 2, "{:?}", c.problems);
        assert!(c.sections[0].credits.is_empty());
    }

    #[test]
    fn change_records_prefer_the_installed_copy() {
        let dir = std::env::temp_dir().join(format!("obs-credits {}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        let obr = dir.join("tahot.obr");
        let mut m = Manifest::new(
            "tahot",
            "TAHOT",
            "TAHOT",
            obs_model::ResourceType::Bible,
            "hbo",
        );
        m.license = "CC-BY-4.0".into();
        m.origin = obs_model::Origin::Starter;
        assert_eq!(
            changes_record_for(&m, &obr).as_deref(),
            Some(
                "https://github.com/inhesrom/openbiblesoftware/releases/latest/download/\
                 CHANGES-tahot.md"
            )
        );
        std::fs::write(dir.join("CHANGES-tahot.md"), "# Changes").unwrap();
        let url = changes_record_for(&m, &obr).unwrap();
        assert!(url.starts_with("file:///"), "{url}");
        assert!(url.ends_with("/CHANGES-tahot.md"), "{url}");
        assert!(url.contains("obs-credits%20"), "{url}");
        assert!(!url.contains('\\'), "{url}");
        m.origin = obs_model::Origin::Imported;
        assert_eq!(changes_record_for(&m, &obr), None);
        std::fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn file_urls_are_portable() {
        assert_eq!(file_url(Path::new("/a b/c#1.md")), "file:///a%20b/c%231.md");
        // A Windows path, as `to_string_lossy` gives it.
        assert_eq!(
            file_url(Path::new(r"C:\Users\me\CHANGES-x.md")),
            "file:///C:/Users/me/CHANGES-x.md"
        );
    }
}
